"""Regression tests for false positives and parser gaps first seen on real public PBIP projects.

The fixtures are synthetic reproductions (``fixtures/realworld`` and ``fixtures/fabric``,
generated by ``build_fixtures.py``); no real project content is used.
"""

import io
import json
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import scan  # noqa: E402
from pbip_audit.checks import Options  # noqa: E402
from pbip_audit.schemas import check_document, load_cache  # noqa: E402
from validate_findings import semantic_checks, validate  # noqa: E402

FIX = HERE / "fixtures"
SCHEMA = json.loads((HERE.parent.parent / "report-schema.json").read_text(encoding="utf-8"))
OPTS = Options(as_of_year=2026)


def findings(result, rule_id, contains=""):
    return [f for f in result["findings"] if f["rule_id"] == rule_id and contains in f["message"]]


class RealWorldRegressionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.result = scan.build_result(FIX / "realworld", OPTS)
        cls.unused = " ".join(f["message"] for f in findings(cls.result, "MOD-10"))

    def test_schema_valid(self):
        self.assertEqual(validate(self.result, SCHEMA, SCHEMA) + semantic_checks(self.result), [])

    # S1: DAX in functions, calculation items, format string expressions and KPIs
    def test_s1_measures_used_only_outside_measures_are_used(self):
        for name in ("Used By Function", "Used By Calc Item", "Used By Format", "Used By Kpi"):
            self.assertNotIn(name, self.unused)

    def test_s1_calculation_item_division_is_checked(self):
        hits = findings(self.result, "DAX-01", "'Ratio'")
        self.assertEqual(len(hits), 1)
        self.assertEqual(hits[0]["evidence"][0]["file"], "Regressions.SemanticModel/definition/tables/View As.tmdl")
        self.assertEqual(hits[0]["evidence"][0]["line"], 7)

    # S2: field parameter Fields columns
    def test_s2_field_parameter_columns_are_used(self):
        self.assertNotIn("Metric Picker Fields", self.unused)
        self.assertNotIn("Axis Picker Fields", self.unused)

    # S3: calculated tables that copy a table or name Table[Column] in sourceColumn
    def test_s3_whole_table_and_source_column_use(self):
        self.assertNotIn("'Period Template'", self.unused)
        self.assertNotIn("'Code Base'", self.unused)

    # S4: Back action on a shape
    def test_s4_back_action_on_a_shape(self):
        self.assertEqual(findings(self.result, "IN-07"), [])

    # S5: page background image
    def test_s5_contrast_skipped_over_a_background_image(self):
        self.assertEqual(findings(self.result, "A11Y-05", "Image Background"), [])

    # S6: new card visual tile fill
    def test_s6_card_visual_fill_is_the_background(self):
        self.assertEqual(findings(self.result, "A11Y-05", "Card Fill"), [])

    # S7: visuals hidden through a hidden group
    def test_s7_hidden_group_children_are_hidden(self):
        self.assertEqual(findings(self.result, "PERF-01", "Hidden Group"), [])
        self.assertEqual(findings(self.result, "A11Y-01", "Hidden Group"), [])

    # S8: group children are positioned relative to their group
    def test_s8_group_offsets_in_tab_order(self):
        self.assertEqual(findings(self.result, "A11Y-04", "Group Offsets"), [])

    # S9: a measure that is one string literal is textual
    def test_s9_single_literal_measures_need_no_format(self):
        names = " ".join(f["message"] for f in findings(self.result, "DAX-07"))
        self.assertNotIn("Brand Teal", names)
        self.assertNotIn("Short Date Pattern", names)

    # S10: time intelligence over a relationship between dateTime columns
    def test_s10_no_mod04_over_a_datetime_relationship(self):
        self.assertEqual(findings(self.result, "MOD-04"), [])

    def test_s10_fact_side_date_column_still_fires_mod04(self):
        import shutil
        with tempfile.TemporaryDirectory() as tmp:
            proj = Path(tmp) / "realworld"
            shutil.copytree(str(FIX / "realworld"), str(proj))
            sales = proj / "Regressions.SemanticModel" / "definition" / "tables" / "Sales.tmdl"
            text = sales.read_text(encoding="utf-8").replace(
                "\t/// Revenue.\n",
                "\tmeasure 'Revenue YTD' = CALCULATE([Revenue], DATESYTD(Sales[SaleDate]))\n\t\tformatString: #,0\n\n\t/// Revenue.\n", 1)
            sales.write_text(text, encoding="utf-8")
            result = scan.build_result(proj, OPTS)
        hit = findings(result, "MOD-04")
        self.assertEqual(len(hit), 1)
        self.assertIn("Revenue YTD", json.dumps(hit[0]))

    # S11: BIND-01 / BIND-03 severity by location
    def test_s11_stale_only_references_are_medium(self):
        for prop, where in (("Old Sort Column", "sort definition"), ("Old Width Column", "formatting selector"),
                            ("Old Filter Measure", "filter card without a condition")):
            hit = findings(self.result, "BIND-01", f"'Sales'[{prop}]")
            self.assertEqual(len(hit), 1, prop)
            self.assertEqual(hit[0]["severity"], "Medium", prop)
            self.assertIn(where, hit[0]["message"])
            self.assertIn("still have their own fields", hit[0]["message"])
            self.assertEqual(hit[0]["evidence"][0]["file"], "Regressions.Report/definition/pages/overview/visuals/staleTable/visual.json")
            self.assertIsNotNone(hit[0]["evidence"][0].get("line"))
        bm = findings(self.result, "BIND-03", "Filtered view")
        self.assertEqual([f["severity"] for f in bm], ["Medium"])

    def test_s11_filter_with_condition_stays_critical(self):
        hit = findings(self.result, "BIND-01", "'Sales'[Old Condition Column]")
        self.assertEqual([f["severity"] for f in hit], ["Critical"])
        self.assertEqual(hit[0]["count"], 2)

    # S14: alt text bound to a measure
    def test_s14_alt_text_bound_to_a_measure(self):
        self.assertEqual(findings(self.result, "A11Y-01", "Overview"), [])


class FabricLayoutTests(unittest.TestCase):
    # S12: Fabric Git layout without a .pbip file
    def test_s12_report_folder_without_pbip(self):
        res = scan.build_result(FIX / "fabric", OPTS)
        t = res["target"]
        self.assertIsNone(t["pbip"])
        self.assertEqual((t["report_path"], t["model_path"]), ("Shop.Report", "Shop.SemanticModel"))
        self.assertEqual((t["report_format"], t["model_format"]), ("PBIR", "TMDL"))
        self.assertTrue(any("No .pbip file" in n for n in res.get("notes", [])))
        self.assertTrue(all(e["file"].startswith(("Shop.Report/", "Shop.SemanticModel/"))
                            for f in res["findings"] for e in f["evidence"]))
        self.assertEqual(validate(res, SCHEMA, SCHEMA) + semantic_checks(res), [])

    def test_s12_semantic_model_folder_only(self):
        res = scan.build_result(FIX / "fabric" / "Shop.SemanticModel", OPTS)
        self.assertEqual((res["target"]["report_format"], res["target"]["model_format"]), ("none", "TMDL"))
        self.assertTrue(any("no report" in n for n in res.get("notes", [])))

    def test_s12_cli_and_several_candidates(self):
        with redirect_stdout(io.StringIO()):
            self.assertEqual(scan.main([str(FIX / "fabric"), "--format", "md"]), 0)
        with tempfile.TemporaryDirectory() as tmp:
            for name in ("A", "B"):
                rep = Path(tmp) / f"{name}.Report"
                rep.mkdir()
                (rep / "definition.pbir").write_text('{"version": "4.0", "datasetReference": {}}', encoding="utf-8")
            err = io.StringIO()
            with redirect_stdout(io.StringIO()), redirect_stderr(err):
                self.assertEqual(scan.main([tmp]), 1)
            self.assertIn("pass one explicitly", err.getvalue())
            self.assertIn("A.Report", err.getvalue())


class NotAssessedScoreTests(unittest.TestCase):
    # S13: pillars without PBIR / TMDL files are not assessed
    def test_s13_tmsl_model_pillars_not_assessed(self):
        res = scan.build_result(FIX / "tmsl", OPTS)
        sc = res["scores"]
        for p in ("model", "dax"):
            self.assertIsNone(sc["pillars"][p]["score"], p)
            self.assertFalse(sc["pillars"][p]["assessed"], p)
        assessed = [row["score"] for p, row in sc["pillars"].items() if row["assessed"] and p not in ("domain",)]
        self.assertEqual(len(assessed), 7)
        self.assertEqual(sc["overall"], round(sum(assessed) / len(assessed)))
        self.assertIn("assessed", sc["formula"])
        self.assertEqual(res["schema_version"], "1.2")
        self.assertEqual(validate(res, SCHEMA, SCHEMA) + semantic_checks(res), [])

    def test_s13_legacy_report_pillars_not_assessed_in_markdown(self):
        res = scan.build_result(FIX / "legacy", OPTS)
        sc = res["scores"]
        self.assertEqual([p for p, row in sc["pillars"].items() if row["assessed"]], ["governance"])
        self.assertEqual(sc["overall"], sc["pillars"]["governance"]["score"])
        md = scan.to_markdown(res)
        self.assertIn("| Accessibility | not assessed |", md)
        self.assertIn("mean of the 1 assessed pillars", md)
        self.assertIn("(1 of 9 pillars assessed)", md.split("## Score per pillar")[0])

    def test_s13_validator_rejects_score_on_not_assessed_pillar(self):
        res = scan.build_result(FIX / "tmsl", OPTS)
        res["scores"]["pillars"]["model"]["score"] = 100
        self.assertTrue(any("not assessed but scored" in e for e in semantic_checks(res)))


class SchemaCacheTests(unittest.TestCase):
    # S15: schema versions published since the cache was first built
    def test_s15_cache_has_current_versions(self):
        cache = load_cache()
        for kind, version in (("page", "1.4.0"), ("report", "1.3.0"), ("visualContainer", "1.6.0")):
            self.assertIsNotNone(check_document({}, kind, version, cache), f"{kind} {version}")

    def test_definition_properties_schema_is_cached_and_checked(self):
        self.assertIsNotNone(check_document({}, "definitionProperties", "2.0.0", load_cache()))
        res = scan.build_result(FIX / "realworld", Options(as_of_year=2026, validate_schemas=True))
        unchecked = " ".join(e.get("detail", "") for f in findings(res, "GOV-18") for e in f["evidence"])
        self.assertNotIn("definitionProperties", unchecked)
        self.assertFalse(any(e["file"].endswith("definition.pbir") for f in findings(res, "GOV-17") for e in f["evidence"]))


if __name__ == "__main__":
    unittest.main()
